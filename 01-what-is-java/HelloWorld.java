// Lesson 1: your first Java program
// Run:  javac HelloWorld.java   then   java HelloWorld

public class HelloWorld {
    public static void main(String[] args) {
        // println prints text and then moves to a new line
        System.out.println("Hello, World!");
        System.out.println("Ku soo dhawoow Java!");

        // print stays on the same line
        System.out.print("Java ");
        System.out.print("is ");
        System.out.println("fun!");

        /* This is a multi-line comment.
           Java ignores everything in here. */
    }
}
